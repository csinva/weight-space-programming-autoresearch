#!/usr/bin/env python
"""Distill the (gitignored) search runs down to the committable ``runs/best/`` tree.

A full run folder is 100s of MB (``search.db`` + every archived model), so it is never committed.
This script extracts just the WINNERS: the single best ``model.py`` per ``(dataset, subject-config)``
group, copied byte-for-byte (below a provenance header) so the champions can be shared and committed.
Idempotent -- re-run after any search to refresh ``runs/best/``.

Grouping key is ``(dataset, subjects)`` because ``test_corr`` is only comparable within one subject
config (NSD scored on subject 1 is a different reward than the mean over 1,2). A run's scoring
subjects come from its ``env.json`` (written at scaffold by ``scripts/setup_run.py``). Runs scaffolded
before ``env.json`` existed have no such record -- their subjects live in ``LEGACY_SUBJECTS`` below
(recovered from each run's eval log + the operator). A run with neither is skipped.

    python scripts/export_champions.py        # regenerate runs/best/ + its README.md
"""
import glob
import json
import os
import shutil
import sqlite3

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEST = os.path.join(REPO, "runs", "best")

# Pre-env.json runs -> the subjects the EVALUATOR scored under (from eval logs + the operator).
# Runs absent here AND without env.json are skipped: unknown config, vanilla baselines, or duplicates
# (e.g. nsd__2026-07-01-vanilla, nsd__champion-p00, nnn__2026-07-07).
LEGACY_SUBJECTS = {
    "nsd__2026-06-22": "1", "nsd__2026-06-23": "1", "nsd__2026-06-24": "1",
    "nsd__2026-06-26": "1", "nsd__2026-06-27": "1", "nsd__2026-06-29": "1,2",
    "nsd__2026-07-04": "1,2", "nsd__2026-07-14": "1,2",
    "ieeg__2026-07-02": "01,02,03", "ieeg__2026-07-03": "01,02,03", "ieeg__2026-07-07": "01,02,03",
    "nnn__2026-07-08": "1,3,4", "nnn__2026-07-15": "1,2,3",
}

CHAMP_SQL = ("SELECT id, dataset, idea, proposer, n_params, test_corr FROM models "
             "WHERE status='ok' AND test_corr IS NOT NULL ORDER BY test_corr DESC LIMIT 1")


def subjects_of(run_dir):
    """The subject config a run scored under: env.json first (authoritative), else the legacy map."""
    env = os.path.join(run_dir, "env.json")
    if os.path.exists(env):
        val = json.load(open(env)).get("NEURO_SUBJECT", "").strip()
        if val:
            return val
    return LEGACY_SUBJECTS.get(os.path.basename(run_dir))


def tag(subjects):
    """'1,2' -> 'subj1-2'; '01,02,03' -> 'subj01-02-03' (folder name for a subject config)."""
    return "subj" + "-".join(p.strip() for p in subjects.split(",") if p.strip())


def champion(db):
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    try:
        return con.execute(CHAMP_SQL).fetchone()
    finally:
        con.close()


def header(champ):
    n = f"{champ['n_params']:,}" if champ["n_params"] is not None else "?"
    bar = "# " + "=" * 78 + "\n"
    return (bar +
            "# runs/best champion -- auto-generated by scripts/export_champions.py (do not edit)\n"
            f"# dataset: {champ['dataset']}   subjects: {champ['subjects']}   "
            f"test_corr: {champ['test_corr']:.4f}   n_params: {n}\n"
            f"# source run: {champ['run']}   model id: {champ['id']}   proposer: {champ['proposer']}\n"
            f"# idea: {champ['idea']}\n" + bar + "\n")


def write_readme(champs):
    lines = [
        "# Best models (`runs/best/`)",
        "",
        "The single best `model.py` per `(dataset, subject-config)`, distilled from the gitignored",
        "search runs by `scripts/export_champions.py`. Each `model.py` is the champion's source copied",
        "verbatim below a provenance header; regenerate with `python scripts/export_champions.py`.",
        "",
        "`test_corr` is comparable **only within the same (dataset, subjects) group** -- NSD/`nnn`",
        "scores are noise-ceiling-normalized, `ieeg` is raw mean r, and different subject sets are",
        "different rewards. See the top-level `CLAUDE.md` for the scoring details.",
        "",
        "| Dataset | Subjects | test_corr | n_params | Model | Source run | Idea |",
        "|---------|----------|-----------|----------|-------|------------|------|",
    ]
    for c in champs:
        n = f"{c['n_params']:,}" if c["n_params"] is not None else "?"
        idea = (c["idea"] or "").replace("|", "\\|")
        lines.append(f"| {c['dataset']} | {c['subjects']} | {c['test_corr']:.4f} | {n} | "
                     f"`{c['id']}` | {c['run']} | {idea} |")
    lines.append("")
    with open(os.path.join(BEST, "README.md"), "w") as f:
        f.write("\n".join(lines))


def main():
    # Best candidate per (dataset, subjects) across all runs that expose a known subject config.
    best = {}
    for db in sorted(glob.glob(os.path.join(REPO, "runs", "*", "search.db"))):
        run_dir = os.path.dirname(db)
        run = os.path.basename(run_dir)
        subjects = subjects_of(run_dir)
        if not subjects:
            print(f"skip {run}: no env.json / legacy subject")
            continue
        champ = champion(db)
        if not champ:
            print(f"skip {run}: no scored model")
            continue
        src = os.path.join(run_dir, "models", f"{champ['id']}.py")
        if not os.path.exists(src):
            print(f"skip {run}: missing source {os.path.relpath(src, REPO)}")
            continue
        key = (champ["dataset"], subjects)
        if key not in best or champ["test_corr"] > best[key]["test_corr"]:
            best[key] = {**dict(champ), "run": run, "subjects": subjects, "src": src}

    # Rebuild runs/best/ from scratch (drop stale dataset dirs; keep README fresh).
    for d in glob.glob(os.path.join(BEST, "*")):
        if os.path.isdir(d):
            shutil.rmtree(d)
    os.makedirs(BEST, exist_ok=True)

    champs = sorted(best.values(), key=lambda c: (c["dataset"], c["subjects"]))
    for c in champs:
        dst_dir = os.path.join(BEST, c["dataset"], tag(c["subjects"]))
        os.makedirs(dst_dir, exist_ok=True)
        with open(os.path.join(dst_dir, "model.py"), "w") as f:
            f.write(header(c) + open(c["src"]).read())
        rel = f"runs/best/{c['dataset']}/{tag(c['subjects'])}/model.py"
        print(f"wrote {rel}  <- {c['run']}/{c['id']} ({c['test_corr']:.4f})")

    write_readme(champs)
    print(f"\n{len(champs)} champion(s) -> runs/best/  (+ README.md)")


if __name__ == "__main__":
    main()
