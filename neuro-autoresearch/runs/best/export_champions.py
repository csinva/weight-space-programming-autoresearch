#!/usr/bin/env python
"""Export one committable champion per dataset's canonical search cohort.

Full search runs remain gitignored. This script selects the best run matching each cohort declared
in ``experiments/evaluation/datasets.py`` and writes ``runs/best/<dataset>/model.py``. A sibling
``evaluation.json`` is preserved only when its champion hash still matches the exported source.
"""
import glob
import hashlib
import json
import os
import sqlite3
import sys

BEST = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(BEST))
sys.path.insert(0, REPO)

from experiments.evaluation.datasets import DATASETS  # noqa: E402

LEGACY_SUBJECTS = {
    "nsd__2026-06-22": "1", "nsd__2026-06-23": "1", "nsd__2026-06-24": "1",
    "nsd__2026-06-26": "1", "nsd__2026-06-27": "1", "nsd__2026-06-29": "1,2",
    "nsd__2026-07-04": "1,2,5,7", "nsd__2026-07-14": "1,2",
    "ieeg__2026-07-07": "01,02,03",
    "nnn__2026-07-08": "1,3,4", "nnn__2026-07-15": "1,2,3",
}

CHAMP_SQL = ("SELECT id, dataset, idea, proposer, n_params, test_corr FROM models "
             "WHERE status='ok' AND test_corr IS NOT NULL ORDER BY test_corr DESC LIMIT 1")


def normalize_subjects(value):
    return ",".join(part.strip() for part in str(value or "").split(",") if part.strip())


def subjects_of(run_dir):
    env = os.path.join(run_dir, "env.json")
    if os.path.exists(env):
        value = normalize_subjects(json.load(open(env)).get("NEURO_SUBJECT"))
        if value:
            return value
    return LEGACY_SUBJECTS.get(os.path.basename(run_dir))


def champion(db):
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    try:
        return con.execute(CHAMP_SQL).fetchone()
    finally:
        con.close()


def header(champ):
    n_params = f"{champ['n_params']:,}" if champ["n_params"] is not None else "?"
    bar = "# " + "=" * 78 + "\n"
    return (bar
            + "# runs/best champion -- generated by runs/best/export_champions.py (do not edit)\n"
            + f"# dataset: {champ['dataset']}   subjects: {champ['subjects']}   "
              f"test_corr: {champ['test_corr']:.4f}   n_params: {n_params}\n"
            + f"# source run: {champ['run']}   model id: {champ['id']}   "
              f"proposer: {champ['proposer']}\n"
            + f"# idea: {champ['idea']}\n" + bar + "\n")


def matching_evaluation(dataset, model_bytes):
    """Return an existing evaluation only if it describes these exact model bytes."""
    path = os.path.join(BEST, dataset, "evaluation.json")
    if not os.path.exists(path):
        return None
    try:
        document = json.load(open(path))
        recorded = document["models"]["champion"]["model_sha256"]
    except (KeyError, TypeError, ValueError, json.JSONDecodeError):
        return None
    return document if recorded == hashlib.sha256(model_bytes).hexdigest() else None


def existing_champion(dataset):
    """Recover README metadata when this machine has no local run for an already exported model."""
    path = os.path.join(BEST, dataset, "model.py")
    if not os.path.exists(path):
        return None
    lines = open(path, errors="replace").readlines()[:8]
    fields = {}
    for line in lines:
        if line.startswith("# dataset:"):
            parts = line[2:].strip().split("   ")
            fields.update(part.split(": ", 1) for part in parts if ": " in part)
        elif line.startswith("# source run:"):
            parts = line[2:].strip().split("   ")
            fields.update(part.split(": ", 1) for part in parts if ": " in part)
        elif line.startswith("# idea:"):
            fields["idea"] = line.split(":", 1)[1].strip()
    try:
        return {
            "dataset": fields["dataset"], "subjects": fields["subjects"],
            "test_corr": float(fields["test_corr"]), "n_params": None,
            "id": fields["model id"], "run": fields["source run"],
            "proposer": fields.get("proposer"), "idea": fields.get("idea"),
        }
    except (KeyError, ValueError):
        return None


def write_readme(champions, evaluated):
    lines = [
        "# Best models (`runs/best/`)",
        "",
        "One champion for each dataset's canonical search cohort. Regenerate the models with",
        "`python runs/best/export_champions.py`, then generate the complete model-first result with",
        "`experiments/evaluation/run.py`. The latter writes `evaluation.json` beside `model.py`.",
        "",
        "An existing evaluation is kept only while its champion SHA256 matches the exported model.",
        "NSD and NNN use noise-normalized r2; TVSD, Huth, and iEEG use raw mean Pearson r.",
        "",
        "| Dataset | Search subjects | Search reward | Model | Source run | Evaluation |",
        "| --- | --- | ---: | --- | --- | --- |",
    ]
    for champ in champions:
        status = "`evaluation.json`" if champ["dataset"] in evaluated else "pending"
        lines.append(
            f"| {champ['dataset']} | {champ['subjects']} | {champ['test_corr']:.4f} | "
            f"`{champ['id']}` | {champ['run']} | {status} |")
    lines.append("")
    with open(os.path.join(BEST, "README.md"), "w") as f:
        f.write("\n".join(lines))


def main():
    best = {}
    for db in sorted(glob.glob(os.path.join(REPO, "runs", "*", "search.db"))):
        run_dir = os.path.dirname(db)
        run = os.path.basename(run_dir)
        subjects = subjects_of(run_dir)
        champ = champion(db)
        if not subjects or not champ or champ["dataset"] not in DATASETS:
            continue
        canonical = ",".join(DATASETS[champ["dataset"]]["search"])
        if subjects != canonical:
            continue
        src = os.path.join(run_dir, "models", f"{champ['id']}.py")
        if not os.path.exists(src):
            continue
        dataset = champ["dataset"]
        if dataset not in best or champ["test_corr"] > best[dataset]["test_corr"]:
            best[dataset] = {**dict(champ), "run": run, "subjects": subjects, "src": src}

    if not best:
        raise SystemExit("no canonical-cohort champions found; runs/best was left unchanged")

    generated, preserved = {}, {}
    for dataset, champ in best.items():
        model_bytes = (header(champ) + open(champ["src"]).read()).encode()
        generated[dataset] = model_bytes
        evaluation = matching_evaluation(dataset, model_bytes)
        if evaluation is not None:
            preserved[dataset] = evaluation

    champions = sorted(best.values(), key=lambda champ: champ["dataset"])
    for champ in champions:
        dataset = champ["dataset"]
        dst = os.path.join(BEST, dataset)
        os.makedirs(dst, exist_ok=True)
        with open(os.path.join(dst, "model.py"), "wb") as f:
            f.write(generated[dataset])
        if dataset in preserved:
            with open(os.path.join(dst, "evaluation.json"), "w") as f:
                json.dump(preserved[dataset], f, indent=2)
                f.write("\n")
        else:
            stale = os.path.join(dst, "evaluation.json")
            if os.path.exists(stale):
                os.remove(stale)
        print(f"wrote runs/best/{dataset}/model.py <- {champ['run']}/{champ['id']} "
              f"({champ['test_corr']:.4f})")

    all_champions = {champ["dataset"]: champ for champ in champions}
    for dataset in DATASETS:
        if dataset not in all_champions:
            old = existing_champion(dataset)
            if old is not None:
                all_champions[dataset] = old
        model = os.path.join(BEST, dataset, "model.py")
        if os.path.exists(model) and dataset not in preserved:
            evaluation = matching_evaluation(dataset, open(model, "rb").read())
            if evaluation is not None:
                preserved[dataset] = evaluation

    write_readme(sorted(all_champions.values(), key=lambda champ: champ["dataset"]), preserved)
    print(f"\n{len(champions)} canonical champion(s) refreshed in runs/best/")


if __name__ == "__main__":
    main()
