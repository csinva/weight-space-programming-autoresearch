"""Score model.py: fit ridge regression on the fitting stories and report the mean voxel correlation
on the visible stories. Appends a row to results/overall_results.csv and saves a snapshot of
model.py to interpretable_transformers_lib/<MODEL_NAME>.py. Do not edit this file."""
import csv, fcntl, importlib.util, os, re, shutil, sys, time
from pathlib import Path
sys.path.insert(0, os.environ['NLBF_CODE'])
import common

here = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('model_meta', here / 'model.py')
meta = importlib.util.module_from_spec(spec); spec.loader.exec_module(meta)
name = re.sub(r'[^A-Za-z0-9_.+-]', '_', meta.MODEL_NAME)
t0 = time.time()
row = dict(model_name=name, visible_corr='', train_corr='', n_features='', seconds='', status='crash', description=meta.MODEL_DESCRIPTION)
lock = open(Path(os.environ['NLBF_WORK']) / 'score.lock', 'w')
fcntl.flock(lock, fcntl.LOCK_EX)  # one scoring at a time across sandboxes (each needs ~10 GB)
try:
    sp = common.split()
    r = common.fit_and_predict(common.load_embedder(here / 'model.py'), sp['fit'], sp['visible'])
    corr = common.voxel_corr(r['Y'], r['pred'])
    row.update(visible_corr=f'{corr.mean():.4f}', train_corr=f"{r['train_corr']:.4f}", n_features=r['n_features'], status='success')
finally:
    fcntl.flock(lock, fcntl.LOCK_UN)
    row['seconds'] = f'{time.time() - t0:.0f}'
    out = here / 'results' / 'overall_results.csv'
    new = not out.exists()
    with out.open('a', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(row))
        if new:
            w.writeheader()
        w.writerow(row)
    (here / 'interpretable_transformers_lib').mkdir(exist_ok=True)
    shutil.copy(here / 'model.py', here / 'interpretable_transformers_lib' / f'{name}.py')
    print({k: v for k, v in row.items() if k != 'description'})
